#!/usr/bin/env python3
"""Share identical generated CJK indices without changing glyph data.

Two coverage tiers are rasterized from different source subsets, so their
interval tables differ and cannot share one file:

  * 8/10/12pt  - the "common" tier, 3500 common characters plus the i18n set
  * 14/16/18pt - the "i18n" tier, only the characters the UI strings need

Within a tier every point size indexes the same codepoints at the same glyph
offsets, so the tables are byte-identical and one copy can be linked into all
of them. The offset field is a glyph index (see EpdFont::getGlyph), not a
bitmap offset, which is what makes sharing across sizes safe.
"""

import argparse
from pathlib import Path
import re


# (shared table name, shared header file, point sizes sharing it)
SHARED_GROUPS = (
    ("notosans_cjk_commonIntervals", "notosans_cjk_common_intervals.h", (8, 10, 12)),
    ("notosans_cjk_i18nIntervals", "notosans_cjk_i18n_intervals.h", (14, 16, 18)),
)

# Kept for callers that only care about the common tier.
SHARED_NAME = SHARED_GROUPS[0][0]
SHARED_FILE = SHARED_GROUPS[0][1]


def _parse_table(body):
    return [tuple(int(value, 16) for value in row)
            for row in re.findall(r"\{\s*(0x[\dA-F]+),\s*(0x[\dA-F]+),\s*(0x[\dA-F]+)\s*\}", body)]


def _read(path):
    """Read a header and normalize its line endings to LF for matching."""
    return path.read_bytes().decode("utf-8").replace("\r\n", "\n")


def _write(path, content, newline=None):
    """Write a header, keeping the line ending the file already uses."""
    if newline is None:
        newline = "\r\n" if path.exists() and b"\r\n" in path.read_bytes() else "\n"
    data = content.encode("utf-8")
    if newline == "\r\n":
        data = data.replace(b"\n", b"\r\n")
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_bytes(data)
    temporary.replace(path)


def _newline_of(paths):
    """Pick the line ending the headers already use, so the rewrite keeps it."""
    for path in paths:
        if path.exists() and b"\r\n" in path.read_bytes():
            return "\r\n"
    return "\n"


def _share_group(directory, shared_name, shared_file, sizes):
    """Replace one group's inline tables with a shared header.

    A group whose headers are all absent is skipped, so a caller can work on a
    subset of the tiers. A group that is only partly present is an error.
    """
    headers = []
    tables = []
    present = [size for size in sizes if (directory / f"notosans_cjk_{size}.h").exists()]
    if not present:
        return []
    if len(present) != len(sizes):
        missing = sorted(set(sizes) - set(present))
        raise ValueError(f"{directory}: missing CJK headers for sizes {missing}")
    for size in sizes:
        name = f"notosans_cjk_{size}"
        path = directory / f"{name}.h"
        text = _read(path)
        pattern = rf"static const EpdUnicodeInterval {name}Intervals\[\] = \{{(.*?)\n\}};\n"
        match = re.search(pattern, text, re.S)
        if match:
            body = match[1]
            text = text[:match.start()] + text[match.end():]
            text = text.replace(f"{name}Intervals,", f"{shared_name},")
            text = text.replace('#include "EpdFontData.h"',
                                f'#include "EpdFontData.h"\n#include "{shared_file}"')
        elif f'#include "{shared_file}"' in text and f"{shared_name}," in text:
            shared = _read(directory / shared_file)
            body = re.search(rf"{shared_name}\[\] = \{{(.*?)\n\}};", shared, re.S).group(1)
        else:
            raise ValueError(f"{path}: missing interval table")
        table = _parse_table(body)
        if not table or (tables and table != tables[0]):
            raise ValueError(f"{path}: CJK interval tables differ; refusing to share")
        tables.append(table)
        headers.append((path, text))

    shared = ('// Generated by share-cn-font-intervals.py; do not edit.\n'
              '#pragma once\n#include "EpdFontData.h"\n\n'
              f'inline constexpr EpdUnicodeInterval {shared_name}[] = {{\n')
    shared += ''.join(f'    {{ 0x{first:X}, 0x{last:X}, 0x{offset:X} }},\n'
                      for first, last, offset in tables[0])
    shared += '};\n'
    return [(directory / shared_file, shared), *headers]


def shared_outputs(directory):
    outputs = []
    for shared_name, shared_file, sizes in SHARED_GROUPS:
        outputs.extend(_share_group(directory, shared_name, shared_file, sizes))
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("directory", nargs="?", type=Path,
                        default=Path(__file__).resolve().parent.parent / "builtinFonts")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    # Validate every table before replacing any output.
    outputs = shared_outputs(args.directory)
    for path, content in outputs:
        if path.exists() and _read(path) == content:
            continue
        if args.check:
            raise SystemExit(f"{path}: shared CJK indices need regeneration")
        # A brand new shared header follows the line ending of the fonts it serves.
        newline = None
        if not path.exists():
            group = next((sizes for _, shared, sizes in SHARED_GROUPS if shared == path.name), None)
            if group:
                newline = _newline_of([args.directory / f"notosans_cjk_{size}.h" for size in group])
        _write(path, content, newline)


if __name__ == "__main__":
    main()
